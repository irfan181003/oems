import { useState } from 'react';
import { Link } from 'react-router-dom';
import { employees } from '../../api/endpoints';
import FormField from '../../components/FormField';
import Mono from '../../components/Mono';
import PageHeader from '../../components/PageHeader';
import { ErrorState } from '../../components/States';
import { useToast } from '../../components/Toast';
import { showServerErrors } from '../../lib/forms';
import { HINTS, LABELS } from '../../lib/labels';
import { serverNow } from '../../lib/serverDate';
import useAsync from '../../lib/useAsync';
import { validate } from '../../lib/validators';
import EmployeeInput from './EmployeeInput';
import { REGISTRATION_FIELDS, rules } from './employeeFields';

const EMPTY = Object.fromEntries(REGISTRATION_FIELDS.map((f) => [f, '']));

/** Shows the temporary password once; it is not stored anywhere in the browser. */
function PasswordPanel({ employee, password, onDone }) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(password);
      setCopied(true);
    } catch {
      setCopied(false);
    }
  };
  return (
    <section className="card" aria-labelledby="pw-h" style={{ borderColor: 'var(--warn)' }}>
      <h2 id="pw-h" className="card__title">
        Employee <Mono>{employee.employee_id}</Mono> registered
      </h2>
      <div className="alert alert--warn" role="alert">
        <strong>Shown only once.</strong> Give this temporary password to {employee.employee_name} now. It cannot be shown again.
      </div>
      <div className="toolbar" style={{ alignItems: 'center', marginTop: 16 }}>
        <div className="readonly-value" style={{ fontSize: 20 }}>
          <Mono>{password}</Mono>
        </div>
        <button type="button" className="btn" onClick={copy}>
          {copied ? 'Copied' : 'Copy password'}
        </button>
      </div>
      <p className="muted" style={{ marginTop: 12 }}>
        Login: <Mono>{employee.employee_id}</Mono> or {employee.email} · Role: Employee
      </p>
      <div className="form-actions">
        <Link className="btn btn--primary" to={`/hr/employees/${employee.employee_id}`} onClick={onDone}>
          I have noted it — open the record
        </Link>
        <button type="button" className="btn" onClick={onDone}>
          Register another employee
        </button>
      </div>
    </section>
  );
}

export default function RegisterEmployee() {
  const toast = useToast();
  const now = useAsync(() => serverNow(), []);
  const today = now.data && now.data.today;
  const [form, setForm] = useState(EMPTY);
  const [errors, setErrors] = useState({});
  const [busy, setBusy] = useState(false);
  const [created, setCreated] = useState(null); // { employee, password }

  const set = (e) => setForm((f) => ({ ...f, [e.target.name]: e.target.value }));

  const onSubmit = async (e) => {
    e.preventDefault();
    const all = rules(today);
    const fe = validate(form, Object.fromEntries(REGISTRATION_FIELDS.map((f) => [f, all[f]])));
    setErrors(fe);
    if (Object.keys(fe).length) {
      toast.push({ tone: 'bad', text: 'Please correct the highlighted fields.' });
      return;
    }
    setBusy(true);
    try {
      const body = Object.fromEntries(REGISTRATION_FIELDS.map((f) => [f, typeof form[f] === 'string' ? form[f].trim() : form[f]]));
      const res = await employees.register(body);
      const { temporary_password: password, ...employee } = res.data;
      setCreated({ employee, password });
      setForm(EMPTY);
      setErrors({});
    } catch (err) {
      showServerErrors(err, setErrors, toast, REGISTRATION_FIELDS); // e.g. 409 duplicate e-mail (BR-09)
    } finally {
      setBusy(false);
    }
  };

  if (now.error) return <ErrorState error={now.error} onRetry={now.reload} />;

  return (
    <>
      <PageHeader title="Register Employee" subtitle="All fields are mandatory. The Employee ID is generated by the system." />
      {created ? (
        <PasswordPanel employee={created.employee} password={created.password} onDone={() => setCreated(null)} />
      ) : (
        <form className="card form" onSubmit={onSubmit} noValidate>
          {REGISTRATION_FIELDS.map((f) => (
            <FormField key={f} label={f === 'basic_salary' ? `${LABELS.basic_salary} (₹ per month)` : LABELS[f]} hint={HINTS[f]} error={errors[f]} required>
              <EmployeeInput field={f} value={form[f]} onChange={set} today={today} />
            </FormField>
          ))}
          <div className="form-actions">
            <button type="submit" className="btn btn--primary" disabled={busy || now.loading}>
              {busy ? 'Registering…' : 'Register employee'}
            </button>
            <Link className="btn" to="/hr/employees">
              Cancel
            </Link>
          </div>
        </form>
      )}
    </>
  );
}
